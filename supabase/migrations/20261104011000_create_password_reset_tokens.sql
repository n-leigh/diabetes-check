-- Keep the existing Flask password-reset flow available after cutover.
-- Existing SQLite tokens are not migrated and must be invalidated at cutover.

create table if not exists public.password_reset_tokens (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    token_hash text not null,
    expires_at timestamptz not null,
    used_at timestamptz
);

create index if not exists idx_password_reset_tokens_hash
    on public.password_reset_tokens (token_hash);

alter table public.password_reset_tokens enable row level security;

revoke all on table public.password_reset_tokens from anon, authenticated;
