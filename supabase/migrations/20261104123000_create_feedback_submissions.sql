create table if not exists public.feedback_submissions (
    id bigint generated by default as identity primary key,
    name text,
    message text not null,
    created_at timestamptz not null default now(),
    constraint feedback_submissions_name_length check (name is null or char_length(name) <= 100),
    constraint feedback_submissions_message_length check (char_length(message) between 1 and 4000)
);

create index if not exists idx_feedback_submissions_created_at
    on public.feedback_submissions (created_at desc);

alter table public.feedback_submissions enable row level security;

revoke all on table public.feedback_submissions from anon, authenticated;
