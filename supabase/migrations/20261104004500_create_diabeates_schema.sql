-- DiaBeates application schema.
-- Flask remains the only application data layer in this migration.
-- password_reset_tokens is intentionally excluded; existing tokens are
-- invalidated during cutover.

create table if not exists public.users (
    id bigint generated by default as identity primary key,
    email text not null unique,
    password_hash text not null,
    display_name text not null,
    role text not null default 'user'
        check (role in ('user', 'admin')),
    is_active boolean not null default true,
    created_at timestamptz not null,
    last_login_at timestamptz,
    failed_attempts integer not null default 0,
    locked_until timestamptz,
    consent_at timestamptz not null,
    consent_version text not null
);

create table if not exists public.assessments (
    id bigint generated by default as identity primary key,
    session_id text not null,
    user_id bigint references public.users(id) on delete cascade,
    created_at timestamptz not null,
    rule_matrix_version text not null,
    archived boolean not null default false,
    bmi double precision,
    age_band integer,
    gen_hlth integer,
    sex integer,
    phys_hlth integer,
    ment_hlth integer,
    high_bp boolean,
    high_chol boolean,
    smoker boolean,
    heart_disease boolean,
    stroke boolean,
    diff_walk boolean,
    no_doc_cost boolean,
    diabetes_duration integer,
    blurry_vision boolean
);

create table if not exists public.risk_results (
    id bigint generated by default as identity primary key,
    assessment_id bigint not null references public.assessments(id),
    category text not null
        check (category in (
            'cardiovascular',
            'general_burden',
            'neuropathy_mobility',
            'retinopathy'
        )),
    rule_score integer,
    rule_percentage integer,
    rule_label text,
    model_name text,
    model_label text,
    model_confidence double precision,
    unique (assessment_id, category)
);

create table if not exists public.lab_assessments (
    id bigint generated by default as identity primary key,
    assessment_id bigint not null unique references public.assessments(id),
    hba1c double precision,
    systolic_bp double precision,
    ldl double precision,
    label text,
    percentage integer
);

create table if not exists public.feedback (
    id bigint generated by default as identity primary key,
    assessment_id bigint not null references public.assessments(id),
    helpful boolean not null,
    comment text,
    created_at timestamptz not null
);

create table if not exists public.audit_log (
    id bigint generated by default as identity primary key,
    actor_user_id bigint references public.users(id) on delete set null,
    action text not null,
    target text,
    ip text,
    created_at timestamptz not null
);

create index if not exists idx_assessments_session_archived_id
    on public.assessments (session_id, archived, id);

create index if not exists idx_assessments_created_at
    on public.assessments (created_at);

create index if not exists idx_risk_results_assessment_id
    on public.risk_results (assessment_id);

create index if not exists idx_lab_assessments_assessment_id
    on public.lab_assessments (assessment_id);

create index if not exists idx_users_email
    on public.users (email);

create index if not exists idx_assessments_user_archived_id
    on public.assessments (user_id, archived, id);

create index if not exists idx_audit_log_created_at
    on public.audit_log (created_at);

-- Deny by default for Data API roles. Flask will use a separate
-- server-side database role and enforce ownership in Python.
alter table public.users enable row level security;
alter table public.assessments enable row level security;
alter table public.risk_results enable row level security;
alter table public.lab_assessments enable row level security;
alter table public.feedback enable row level security;
alter table public.audit_log enable row level security;

revoke all on table
    public.users,
    public.assessments,
    public.risk_results,
    public.lab_assessments,
    public.feedback,
    public.audit_log
from anon, authenticated;
