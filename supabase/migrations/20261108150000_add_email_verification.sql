-- Email verification for DiaBeates accounts.
-- Run only after taking a database backup.

do $$
declare
    column_was_present boolean;
begin
    select exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'users'
          and column_name = 'email_verified_at'
    ) into column_was_present;
    if not column_was_present then
        alter table public.users add column email_verified_at timestamptz;
        update public.users
        set email_verified_at = created_at
        where email_verified_at is null;
    end if;
end $$;

create table if not exists public.email_verification_tokens (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    token_hash text not null,
    expires_at timestamptz not null,
    used_at timestamptz
);

create index if not exists idx_email_verification_tokens_hash
    on public.email_verification_tokens (token_hash);
create unique index if not exists idx_email_verification_tokens_unique_hash
    on public.email_verification_tokens (token_hash);
create index if not exists idx_email_verification_tokens_user_id
    on public.email_verification_tokens (user_id);
create index if not exists idx_email_verification_tokens_expires_at
    on public.email_verification_tokens (expires_at);

alter table public.email_verification_tokens enable row level security;
revoke all on table public.email_verification_tokens from anon, authenticated;
